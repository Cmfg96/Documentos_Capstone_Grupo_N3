create or replace function public.registrar_cambio_estado_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (tg_op = 'INSERT') then
    insert into public.historial_pedido(pedido_id, estado_anterior, estado_nuevo, cambiado_por)
    values (new.id, null, new.estado, auth.uid());
  elsif (tg_op = 'UPDATE' and new.estado is distinct from old.estado) then
    insert into public.historial_pedido(pedido_id, estado_anterior, estado_nuevo, cambiado_por)
    values (new.id, old.estado, new.estado, auth.uid());
  end if;
  return new;
end;
$$;
create trigger trg_historial_pedido
  after insert or update of estado on public.pedidos
  for each row execute function public.registrar_cambio_estado_pedido();

