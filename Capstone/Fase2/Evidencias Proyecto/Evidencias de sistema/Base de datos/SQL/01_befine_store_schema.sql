create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.perfiles (id, nombre)
  values (new.id, coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email,'@',1)));
  return new;
end;
$$;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Impide que un cliente se auto-escale rol/nivel/puntos al editar su perfil
create or replace function public.proteger_campos_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not public.es_admin() then
    new.rol             := old.rol;
    new.nivel_precio_id := old.nivel_precio_id;
    new.puntos_saldo    := old.puntos_saldo;
  end if;
  return new;
end;
$$;
create trigger trg_proteger_perfil before update on public.perfiles
  for each row execute function public.proteger_campos_perfil();

