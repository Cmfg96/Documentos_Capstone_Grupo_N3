-- Precio del producto según el nivel del cliente (retail o B2B)
create or replace function public.precio_efectivo(p_perfil uuid, p_variante uuid)
returns integer language sql stable security definer set search_path = public as $$
  select pv.precio
    from public.precios_variante pv
    join public.perfiles pf on pf.id = p_perfil
   where pv.variante_id = p_variante and pv.nivel_precio_id = pf.nivel_precio_id;
$$;

